USE WAREHOUSE COMPUTE_WH;
USE DATABASE WALMART_DB;
USE SCHEMA RAW;

CREATE OR REPLACE STAGE WALMART_DB.RAW.MY_S3_STAGE
  URL = 's3://walmart-data-pipeline-tableworld/'
  STORAGE_INTEGRATION = s3_init_integration;

CREATE OR REPLACE FILE FORMAT WALMART_CSV_FMT
    TYPE = CSV
    FIELD_DELIMITER = ','
    SKIP_HEADER = 1
    FIELD_OPTIONALLY_ENCLOSED_BY = '"'
    NULL_IF = ('NULL', 'null', 'NA', 'N/A', '')
    EMPTY_FIELD_AS_NULL = TRUE;

-- 1. Load stores.csv -> RAW_STORES
COPY INTO RAW_STORES
FROM @WALMART_DB.RAW.MY_S3_STAGE/stores.csv
FILE_FORMAT = (FORMAT_NAME = WALMART_CSV_FMT)
ON_ERROR = 'ABORT_STATEMENT';

-- 2. Load fact.csv -> RAW_FACT
COPY INTO RAW_FACT
FROM @WALMART_DB.RAW.MY_S3_STAGE/fact.csv
FILE_FORMAT = (FORMAT_NAME = WALMART_CSV_FMT)
ON_ERROR = 'ABORT_STATEMENT';

-- 3. Load department.csv -> RAW_DEPARTMENT
COPY INTO RAW_DEPARTMENT
FROM @WALMART_DB.RAW.MY_S3_STAGE/department.csv
FILE_FORMAT = (FORMAT_NAME = WALMART_CSV_FMT)
ON_ERROR = 'ABORT_STATEMENT';

SELECT 'RAW_STORES' AS TABLE_NAME, COUNT(*) AS ROW_COUNT FROM WALMART_DB.RAW.RAW_STORES
UNION ALL
SELECT 'RAW_FACT', COUNT(*) FROM WALMART_DB.RAW.RAW_FACT
UNION ALL
SELECT 'RAW_DEPARTMENT', COUNT(*) FROM WALMART_DB.RAW.RAW_DEPARTMENT;

SHOW TABLES LIKE 'WALMART_%' IN DATABASE WALMART_DB;
